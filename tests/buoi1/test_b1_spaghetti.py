import re

from playwright.sync_api import expect


def test_spaghetti_search_pliers(page):
    page.goto("/")
    expect(page.get_by_test_id("product-name").first).to_be_visible()  # wait for the initial list first
    page.get_by_test_id("search-query").fill("pliers")
    page.get_by_test_id("search-submit").click()
    expect(page.get_by_test_id("search_completed")).to_be_visible()
    names = page.get_by_test_id("product-name").all_inner_texts()
    assert names and all("pliers" in n.lower() for n in names)


def test_spaghetti_add_two_hammers(page):
    page.goto("/")
    expect(page.get_by_test_id("product-name").first).to_be_visible()
    page.get_by_test_id("product-name").filter(has_text=re.compile(r"^\s*Claw Hammer\s*$")).click()
    expect(page.get_by_test_id("product-name")).to_have_text("Claw Hammer")
    page.get_by_test_id("quantity").fill("2")
    page.get_by_test_id("add-to-cart").click()
    expect(page.get_by_test_id("cart-quantity")).to_have_text("2")


def test_spaghetti_search_then_open_first_product(page):
    page.goto("/")
    expect(page.get_by_test_id("product-name").first).to_be_visible()
    page.get_by_test_id("search-query").fill("saw")
    page.get_by_test_id("search-submit").click()
    expect(page.get_by_test_id("search_completed")).to_be_visible()
    first = page.get_by_test_id("product-name").first.inner_text()
    page.get_by_test_id("product-name").first.click()
    # to_contain_text, not to_have_text: eco products render an "ECO" badge inside the same h1
    expect(page.get_by_test_id("product-name")).to_contain_text(first)


def test_spaghetti_login_wrong_password(page):
    # Never try wrong passwords on the shared accounts: Toolshop counts failed_login_attempts
    # and can lock the account for the whole class. An address with no account is safe.
    page.goto("/auth/login")
    page.get_by_test_id("email").fill("nobody-here@example.com")
    page.get_by_test_id("password").fill("Wrong-Password-123")
    page.get_by_test_id("login-submit").click()
    expect(page.get_by_test_id("login-error")).to_contain_text("Invalid email or password")
